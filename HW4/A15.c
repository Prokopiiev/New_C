#include <stdio.h>

int main() {
    int x1, y1, x2, y2;
    
    // Считываем координаты двух точек
    scanf("%d %d %d %d", &x1, &y1, &x2, &y2);
    
    // Вычисляем угловой коэффициент k
    // Приводим к double, чтобы избежать целочисленного деления
    double k = (double)(y2 - y1) / (x2 - x1);
    
    // Вычисляем свободный член b: b = y1 - k * x1
    double b = y1 - k * x1;
    
    // Выводим результат с двумя знаками после запятой
    printf("%.2f %.2f\n", k, b);
    
    return 0;
}
